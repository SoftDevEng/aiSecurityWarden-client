# action approval (see DESIGN.md "Action approval")
# ---------------------------------------------------------------------------

def action_digest(action: str, args: object) -> str:
    """SHA-256 (hex) of the canonical form of an action: what a person approves is exactly this.

    ``args`` is any JSON value (objects, arrays, strings, integers, booleans, null; no floats, which
    have no single canonical text). Keys are sorted and no whitespace is written, so the same action
    always gives the same digest. Large content (an attachment, a long body) goes in as its own hash."""
    _check_canonical(args)
    canon = json.dumps({"action": action, "args": args}, sort_keys=True, separators=(",", ":"),
                       ensure_ascii=False, allow_nan=False)
    return hashlib.sha256(f"{PREFIX}|action-digest|".encode("utf-8") + canon.encode("utf-8")).hexdigest()


def _check_canonical(v: object) -> None:
    if isinstance(v, float):
        raise CryptoError("action arguments may not contain floating-point numbers (use strings)")
    if isinstance(v, dict):
        for k, x in v.items():
            if not isinstance(k, str):
                raise CryptoError("action argument keys must be strings")
            _check_canonical(x)
    elif isinstance(v, (list, tuple)):
        for x in v:
            _check_canonical(x)
    elif not (v is None or isinstance(v, (str, int, bool))):
        raise CryptoError(f"action arguments must be JSON values, not {type(v).__name__}")


def _aad_action(project_id: str, request_id: str) -> str:
    return f"{PREFIX}|action|{project_id}|{request_id}"


def encrypt_action_summary(project_key: bytes, project_id: str, request_id: str, summary: dict) -> str:
    """The summary a person sees, encrypted under the project key, for projects whose phone messages
    must not carry content. Bound to its project and request id."""
    k = hkdf(project_key, b"securitywarden/v1/action-summary")
    payload = json.dumps(summary, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return seal(k, payload, _aad_action(project_id, request_id))


def decrypt_action_summary(project_key: bytes, project_id: str, request_id: str, blob: str) -> dict:
    k = hkdf(project_key, b"securitywarden/v1/action-summary")
    data = json.loads(open_(k, blob, _aad_action(project_id, request_id)))
    if not isinstance(data, dict):
        raise CryptoError("action summary is not an object")
    return data


