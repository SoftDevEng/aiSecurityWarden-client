def pkce_pair() -> tuple[str, str]:
    """(code_verifier, code_challenge) for an OAuth sign-in with PKCE, method S256."""
    verifier = b64e(os.urandom(32))
    return verifier, b64e(hashlib.sha256(verifier.encode("ascii")).digest())
