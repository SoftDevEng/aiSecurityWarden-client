# ---------------------------------------------------------------------------
# secrets
# ---------------------------------------------------------------------------

def name_mac(project_key: bytes, name: str) -> str:
    """Deterministic, non-reversible lookup id for a secret name."""
    k = hkdf(project_key, b"securitywarden/v1/name-mac")
    return hmac.new(k, name.encode("utf-8"), hashlib.sha256).hexdigest()


def _aad_secret(project_id: str, mac: str) -> str:
    return f"{PREFIX}|secret|{project_id}|{mac}"


def encrypt_secret(project_key: bytes, project_id: str, name: str, value: str) -> tuple[str, str]:
    """Return (name_mac, blob). Both the name and value are inside the blob."""
    mac = name_mac(project_key, name)
    payload = json.dumps({"n": name, "v": value}, separators=(",", ":")).encode("utf-8")
    k = hkdf(project_key, b"securitywarden/v1/secret-enc")
    return mac, seal(k, payload, _aad_secret(project_id, mac))


def decrypt_secret(project_key: bytes, project_id: str, mac: str, blob: str) -> tuple[str, str]:
    k = hkdf(project_key, b"securitywarden/v1/secret-enc")
    data = json.loads(open_(k, blob, _aad_secret(project_id, mac)))
    name, value = data["n"], data["v"]
    # defence in depth: the name inside must hash to the mac it was stored under
    if not hmac.compare_digest(name_mac(project_key, name), mac):
        raise CryptoError("secret name does not match its lookup id")
    return name, value


