"""Credential format and cryptographic primitives.

Everything security-relevant lives in this one module so it can be reviewed
in isolation. Only well-known primitives from `cryptography` are used:

* AES-256-GCM for all encryption (random 96-bit nonces)
* HKDF-SHA256 for key separation
* HMAC-SHA256 for deterministic secret-name lookup ids

Credential format (same shape for machine and admin credentials)::

    sw1.<kind>.<id>.<secret>:<key>

    kind    "m" = machine token (read-only, one project)
            "a" = admin credential
    id      public identifier, stored in clear on the server
    secret  proves possession; server stores only an Argon2 hash of it
    key     32 random bytes (base64url). NEVER sent to the server. Used
            client-side to unwrap the project key.

Key hierarchy::

    project_key (32 random bytes, generated by the admin client)
      ├─ wrapped under each machine token's wrap key  -> tokens.wrapped_key
      ├─ wrapped under the admin key                  -> projects.wrapped_key
      ├─ HKDF "secret-enc"     -> AES key for secret blobs
      ├─ HKDF "name-mac"       -> HMAC key for secret name lookup ids
      └─ HKDF "action-summary" -> AES key for encrypted action summaries

AAD binds every ciphertext to its context (project id, token id, name mac),
so the server cannot swap blobs between projects, tokens, or names.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import re
import secrets as _secrets
import unicodedata
from dataclasses import dataclass

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC

PREFIX = "sw1"
KIND_MACHINE = "m"
KIND_ADMIN = "a"
KEY_LEN = 32
NONCE_LEN = 12
BLOB_PREFIX = "v1."

ID_RE = re.compile(r"^[A-Za-z0-9_-]{16,64}$")


class CryptoError(Exception):
    """Raised when decryption or credential parsing fails."""


# ---------------------------------------------------------------------------
# encoding helpers
# ---------------------------------------------------------------------------

def b64e(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def b64d(text: str) -> bytes:
    pad = "=" * (-len(text) % 4)
    try:
        return base64.urlsafe_b64decode(text + pad)
    except Exception as e:  # binascii.Error, ValueError
        raise CryptoError("invalid base64") from e


def new_id() -> str:
    """Random public identifier (22 chars, base64url)."""
    return b64e(os.urandom(16))


def new_key() -> bytes:
    return os.urandom(KEY_LEN)


# ---------------------------------------------------------------------------
# approval capabilities and nonces
# ---------------------------------------------------------------------------

CAP_RE = re.compile(r"^[A-Za-z0-9_-]{22}$")


def new_capability() -> str:
    """Single-use, 128-bit random value that lets whoever holds it decide one approval request."""
    return b64e(os.urandom(16))


def new_nonce() -> str:
    """Client nonce binding an approval request to the process that made it (128 bits)."""
    return b64e(os.urandom(16))


def lookup_hash(value: str) -> str:
    """SHA-256 of a capability or nonce. The server stores only this, so a database copy
    cannot be used to approve a request or redeem one."""
    return hashlib.sha256(b"securitywarden/v1/lookup|" + value.encode("utf-8")).hexdigest()


def match_code() -> str:
    """Two-digit code shown both to the requesting client and in the approval prompt."""
    return f"{_secrets.randbelow(100):02d}"


# ---------------------------------------------------------------------------
# credentials
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Credential:
    kind: str
    id: str
    secret: str
    key: bytes

    def __str__(self) -> str:
        return f"{PREFIX}.{self.kind}.{self.id}.{self.secret}:{b64e(self.key)}"

    def __repr__(self) -> str:  # never leak secret/key into logs or tracebacks
        return f"Credential(kind={self.kind!r}, id={self.id!r}, secret=***, key=***)"

    @property
    def wrap_key(self) -> bytes:
        return hkdf(self.key, b"securitywarden/v1/wrap")


def new_credential(kind: str) -> Credential:
    if kind not in (KIND_MACHINE, KIND_ADMIN):
        raise ValueError("kind must be 'm' or 'a'")
    return Credential(kind=kind, id=new_id(), secret=_secrets.token_urlsafe(32), key=new_key())


def parse_credential(text: str) -> Credential:
    text = (text or "").strip()
    try:
        head, key_part = text.rsplit(":", 1)
        prefix, kind, cid, secret = head.split(".", 3)
    except ValueError as e:
        raise CryptoError("malformed credential") from e
    if prefix != PREFIX or kind not in (KIND_MACHINE, KIND_ADMIN):
        raise CryptoError("unsupported credential type")
    if not ID_RE.match(cid) or not secret or "." in secret:
        raise CryptoError("malformed credential")
    key = b64d(key_part)
    if len(key) != KEY_LEN:
        raise CryptoError("malformed credential key")
    return Credential(kind=kind, id=cid, secret=secret, key=key)


# ---------------------------------------------------------------------------
# primitives
# ---------------------------------------------------------------------------

def hkdf(ikm: bytes, info: bytes, length: int = KEY_LEN) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=None, info=info).derive(ikm)


def seal(key: bytes, plaintext: bytes, aad: str) -> str:
    nonce = os.urandom(NONCE_LEN)
    ct = AESGCM(key).encrypt(nonce, plaintext, aad.encode("utf-8"))
    return BLOB_PREFIX + b64e(nonce + ct)


def open_(key: bytes, blob: str, aad: str) -> bytes:
    if not isinstance(blob, str) or not blob.startswith(BLOB_PREFIX):
        raise CryptoError("unsupported blob version")
    raw = b64d(blob[len(BLOB_PREFIX):])
    if len(raw) < NONCE_LEN + 16:
        raise CryptoError("blob too short")
    try:
        return AESGCM(key).decrypt(raw[:NONCE_LEN], raw[NONCE_LEN:], aad.encode("utf-8"))
    except Exception as e:  # InvalidTag
        raise CryptoError("decryption failed (wrong key or tampered data)") from e


