def unwrap_account_key_with_password(blob: str, master: bytes, user_id: str) -> bytes:
    return open_(_account_pw_wrap(master), blob, _aad_account_key(user_id, "password"))


def new_recovery_key() -> bytes:
    return os.urandom(KEY_LEN)


def format_recovery_key(key: bytes) -> str:
    """SWR1-XXXX-XXXX-... (RFC 4648 base32, no padding, groups of four): easy to write down."""
    bits = int.from_bytes(key, "big")
    n = len(key) * 8
    chars = []
    for i in range(0, n, 5):
        shift = n - i - 5
        chars.append(_B32[(bits >> shift) & 31] if shift >= 0 else _B32[(bits << -shift) & 31])
    text = "".join(chars)
    return RECOVERY_PREFIX + "-".join(text[i:i + 4] for i in range(0, len(text), 4))


def parse_recovery_key(text: str) -> bytes:
    """Accepts any case, spaces and dashes. Raises CryptoError."""
    t = re.sub(r"[\s-]", "", (text or "").upper())
    if t.startswith(RECOVERY_PREFIX.rstrip("-")):
        t = t[len(RECOVERY_PREFIX) - 1:]
    if len(t) != 52 or any(c not in _B32 for c in t):
        raise CryptoError("that isn't a SecurityWarden recovery key")
    bits = 0
    for c in t:
        bits = (bits << 5) | _B32.index(c)
    if bits & 0b1111:                    # 52 * 5 = 260 bits: the last 4 are padding and must be zero
        raise CryptoError("that isn't a SecurityWarden recovery key")
    return (bits >> 4).to_bytes(KEY_LEN, "big")


