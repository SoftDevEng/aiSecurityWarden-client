KDF_PBKDF2 = "pbkdf2-sha256"
PBKDF2_MIN_ITERATIONS = 600_000      # OWASP 2023 for PBKDF2-HMAC-SHA256
PBKDF2_MAX_ITERATIONS = 10_000_000
DEFAULT_KDF = {"alg": KDF_PBKDF2, "iterations": PBKDF2_MIN_ITERATIONS}
SALT_LEN = 16
RECOVERY_PREFIX = "SWR1-"
_B32 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"


def check_kdf(kdf: object) -> dict:
    """The KDF parameters an account may use. Raises ValueError."""
    if not isinstance(kdf, dict) or set(kdf) != {"alg", "iterations"} or kdf["alg"] != KDF_PBKDF2:
        raise ValueError("unsupported key derivation")
    n = kdf["iterations"]
    if isinstance(n, bool) or not isinstance(n, int) or not PBKDF2_MIN_ITERATIONS <= n <= PBKDF2_MAX_ITERATIONS:
        raise ValueError(f"iterations must be between {PBKDF2_MIN_ITERATIONS} and {PBKDF2_MAX_ITERATIONS}")
    return {"alg": KDF_PBKDF2, "iterations": n}


def master_key(password: str, salt: bytes, kdf: dict) -> bytes:
    """PBKDF2-HMAC-SHA256 of the NFC-normalised password. Never leaves the client."""
    kdf = check_kdf(kdf)
    pw = unicodedata.normalize("NFC", password).encode("utf-8")
    return PBKDF2HMAC(algorithm=hashes.SHA256(), length=KEY_LEN, salt=salt, iterations=kdf["iterations"]).derive(pw)


def account_auth_key(master: bytes) -> bytes:
    """Proves the password to the server (which stores an Argon2id hash of it). Can't decrypt anything."""
    return hkdf(master, b"securitywarden/v1/account-auth")


def _account_pw_wrap(master: bytes) -> bytes:
    return hkdf(master, b"securitywarden/v1/account-wrap")


def _aad_account_key(user_id: str, how: str) -> str:
    return f"{PREFIX}|account-key|{how}|{user_id}"


def wrap_account_key_with_password(account_key: bytes, master: bytes, user_id: str) -> str:
    return seal(_account_pw_wrap(master), account_key, _aad_account_key(user_id, "password"))


def unwrap_account_key_with_password(blob: str, master: bytes, user_id: str) -> bytes:
    return open_(_account_pw_wrap(master), blob, _aad_account_key(user_id, "password"))


def new_recovery_key() -> bytes:
    return os.urandom(KEY_LEN)


def format_recovery_key(key: bytes) -> str:
    """SWR1-XXXX-XXXX-... (RFC 4648 base32, no padding, groups of four): easy to write down."""
    bits = int.from_bytes(key, "big")
    n = len(key) * 8
    chars = []
    for i in range(0, n, 5):
        shift = n - i - 5
        chars.append(_B32[(bits >> shift) & 31] if shift >= 0 else _B32[(bits << -shift) & 31])
    text = "".join(chars)
    return RECOVERY_PREFIX + "-".join(text[i:i + 4] for i in range(0, len(text), 4))


def parse_recovery_key(text: str) -> bytes:
    """Accepts any case, spaces and dashes. Raises CryptoError."""
    t = re.sub(r"[\s-]", "", (text or "").upper())
    if t.startswith(RECOVERY_PREFIX.rstrip("-")):
        t = t[len(RECOVERY_PREFIX) - 1:]
    if len(t) != 52 or any(c not in _B32 for c in t):
        raise CryptoError("that isn't a SecurityWarden recovery key")
    bits = 0
    for c in t:
        bits = (bits << 5) | _B32.index(c)
    if bits & 0b1111:                    # 52 * 5 = 260 bits: the last 4 are padding and must be zero
        raise CryptoError("that isn't a SecurityWarden recovery key")
    return (bits >> 4).to_bytes(KEY_LEN, "big")


