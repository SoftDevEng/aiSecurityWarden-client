@contextmanager
def seeded(seed: str) -> Iterator[None]:
    """Deterministic os.urandom inside crypto.py, for generating vectors only."""
    counter = [0]

    def fake(n: int) -> bytes:
        out = b""
        while len(out) < n:
            out += hashlib.sha256(f"{seed}|{counter[0]}".encode()).digest()
            counter[0] += 1
        return out[:n]

    real = crypto.os.urandom
    crypto.os.urandom = fake  # type: ignore[assignment]
    try:
        yield
    finally:
        crypto.os.urandom = real  # type: ignore[assignment]


def key(label: str) -> bytes:
    return hashlib.sha256(f"securitywarden-test-vector|{label}".encode()).digest()


def cred(kind: str, label: str) -> crypto.Credential:
    return crypto.Credential(kind=kind, id=crypto.b64e(key(label + "/id")[:16]),
                             secret=crypto.b64e(key(label + "/secret")), key=key(label + "/key"))


