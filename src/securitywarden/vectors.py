            str(m).rsplit(":", 1)[0],                                          # no key part
            str(m).rsplit(":", 1)[0] + ":" + crypto.b64e(b"short"),            # key too short
            str(m).replace(m.id, "short"),                                     # id too short
            str(m).replace(m.secret, "has.dot"),                               # secret with a dot
