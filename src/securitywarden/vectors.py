"""Crypto test vectors (``crypto-v1.json``): every format in :mod:`securitywarden.crypto`, produced with
fixed keys and a seeded random source so the output is deterministic.

Other implementations (the web front end's TypeScript crypto, future clients) check themselves against
these bytes, so no implementation can drift from this one:

* this repo: tests/test_vectors.py checks tests/vectors/crypto-v1.json against :func:`render`.
* the server repo keeps a copy for its web front end and checks the copy against :func:`render` of the
  installed client package.

Write a file:  python -m securitywarden.vectors [PATH]   (default: tests/vectors/crypto-v1.json)
"""

